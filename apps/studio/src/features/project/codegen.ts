import { Cls, FIELD_SIZE, MFR, SysReq, type ModelDef, type StatusFieldDef, type StatusFrameDef } from '@cygnus/protocol';

/**
 * Code snippets for talking to Cygnus boards from other hosts. There are no Cygnus host
 * libraries for Gemstone, Pixhawk or Arduino yet, so everything generated here is limited to
 * constants, CAN identifier arithmetic (PROTOCOL §2) and raw frame examples; it never calls a
 * Cygnus library API. Identifier math is written out here on purpose (not imported from the
 * protocol package) so the tests can check it against the real codecs.
 */

export interface CodeCard {
  name: string;
  devType: number;
  num: number;
  model: number;
  modelKey: string;
  def: ModelDef | undefined;
}

export interface CodeText {
  /** Localised "no host library yet" notice, one line per entry. */
  notice: readonly string[];
  /** Where the cards came from (project name / live bus), for the header comment. */
  source: string;
}

/** PROTOCOL §2: DEVTYPE(5) MFR(8) CLASS(6) INDEX(4) NUM(6) in bits 28..0. */
export function canId(devType: number, cls: number, index: number, num: number): number {
  return (((devType & 0x1f) * 2 ** 24) + ((MFR & 0xff) << 16) + ((cls & 0x3f) << 10) + ((index & 0x0f) << 6) + (num & 0x3f)) >>> 0;
}

const TRANSLIT: Record<string, string> = { ç: 'c', ğ: 'g', ı: 'i', ö: 'o', ş: 's', ü: 'u', Ç: 'C', Ğ: 'G', İ: 'I', Ö: 'O', Ş: 'S', Ü: 'U' };

/** `Sol ön itici` → `SOL_ON_ITICI`; always a valid C / Python identifier. */
export function identOf(name: string, fallback: string): string {
  const ascii = name
    .replace(/[çğıöşüÇĞİÖŞÜ]/g, (c) => TRANSLIT[c] ?? c)
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
  let id = ascii.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (!id) id = fallback.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
  return /^[0-9]/.test(id) ? `_${id}` : id;
}

export interface NamedCard extends CodeCard {
  ident: string;
}

/** Unique identifiers: the second `SOL` becomes `SOL_2`. */
export function nameCards(cards: readonly CodeCard[]): NamedCard[] {
  const used = new Map<string, number>();
  return cards.map((c) => {
    const base = identOf(c.name, `${c.modelKey}_${c.num}`);
    const n = (used.get(base) ?? 0) + 1;
    used.set(base, n);
    return { ...c, ident: n === 1 ? base : `${base}_${n}` };
  });
}

const hex = (n: number): string => `0x${n.toString(16).toUpperCase().padStart(8, '0')}`;
/** A float literal valid in C, C++ and Python. */
const lit = (n: number): string => (Number.isInteger(n) ? `${n}.0` : String(n));
const sig = (key: string): string => key.replace(/[^A-Za-z0-9]+/g, '_');

export interface FrameIds {
  statusIds: Array<{ index: number; id: number; label: string }>;
  ctrlIds: Array<{ index: number; id: number; key: string }>;
  heartbeat: number;
  identify: number;
}

export function frameIds(c: CodeCard): FrameIds {
  return {
    statusIds: (c.def?.statusFrames ?? []).map((f) => ({ index: f.index, id: canId(c.devType, Cls.STATUS, f.index, c.num), label: f.label.en })),
    ctrlIds: (c.def?.controls ?? []).map((f) => ({ index: f.index, id: canId(c.devType, Cls.CTRL, f.index, c.num), key: f.key })),
    heartbeat: canId(c.devType, Cls.SYS_RSP, 0, c.num),
    identify: canId(c.devType, Cls.SYS_REQ, SysReq.IDENTIFY, c.num),
  };
}

const noticeBlock = (text: CodeText, open: string, line: string, close: string): string =>
  [open, ...text.notice.map((l) => `${line}${l}`), close].join('\n');

// ---- C header ----------------------------------------------------------------------------

export function genCHeader(cards: readonly CodeCard[], text: CodeText): string {
  const named = nameCards(cards);
  const out: string[] = [];
  out.push(noticeBlock({ ...text, notice: ['Generated by Cygnus Studio.', `Source: ${text.source}`, '', ...text.notice] }, '/*', ' * ', ' */'));
  out.push('#ifndef CYGNUS_IDS_H', '#define CYGNUS_IDS_H', '', '#include <stdint.h>', '');
  out.push('/* CAN identifier layout (PROTOCOL 2): DEVTYPE[28:24] MFR[23:16] CLASS[15:10] INDEX[9:6] NUM[5:0], 29-bit extended frames. */');
  out.push(`#define CYGNUS_MFR ${MFR}u`);
  out.push(`#define CYGNUS_CLS_CTRL 0x${Cls.CTRL.toString(16)}u`);
  out.push(`#define CYGNUS_CLS_STATUS 0x${Cls.STATUS.toString(16)}u`);
  out.push(`#define CYGNUS_CLS_SYS_REQ 0x${Cls.SYS_REQ.toString(16)}u`);
  out.push(`#define CYGNUS_CLS_SYS_RSP 0x${Cls.SYS_RSP.toString(16)}u`);
  out.push(`#define CYGNUS_SYS_REQ_IDENTIFY ${SysReq.IDENTIFY}u`, '');
  out.push('#define CYGNUS_ID(devtype, cls, index, num) \\');
  out.push('  ((((uint32_t)(devtype) & 0x1Fu) << 24) | (((uint32_t)CYGNUS_MFR & 0xFFu) << 16) | \\');
  out.push('   (((uint32_t)(cls) & 0x3Fu) << 10) | (((uint32_t)(index) & 0x0Fu) << 6) | ((uint32_t)(num) & 0x3Fu))');
  out.push('#define CYGNUS_ID_DEVTYPE(id) (((uint32_t)(id) >> 24) & 0x1Fu)');
  out.push('#define CYGNUS_ID_MFR(id)     (((uint32_t)(id) >> 16) & 0xFFu)');
  out.push('#define CYGNUS_ID_CLS(id)     (((uint32_t)(id) >> 10) & 0x3Fu)');
  out.push('#define CYGNUS_ID_INDEX(id)   (((uint32_t)(id) >> 6) & 0x0Fu)');
  out.push('#define CYGNUS_ID_NUM(id)     ((uint32_t)(id) & 0x3Fu)', '');
  for (const c of named) {
    const ids = frameIds(c);
    out.push(`/* ${c.ident}: ${c.def?.name.en ?? c.modelKey} (model ${c.model}), number ${c.num} */`);
    out.push(`#define ${c.ident}_MODEL ${c.model}u`);
    out.push(`#define ${c.ident}_DEVTYPE ${c.devType}u`);
    out.push(`#define ${c.ident}_NUM ${c.num}u`);
    if (c.def) {
      out.push(`#define ${c.ident}_ID_HEARTBEAT ${hex(ids.heartbeat)}u`);
      out.push(`#define ${c.ident}_ID_IDENTIFY ${hex(ids.identify)}u`);
      for (const s of ids.statusIds) out.push(`#define ${c.ident}_ID_STATUS${s.index} ${hex(s.id)}u  /* ${s.label} */`);
      for (const s of ids.ctrlIds) out.push(`#define ${c.ident}_ID_CTRL${s.index} ${hex(s.id)}u  /* ${s.key} */`);
    }
    out.push('');
  }
  out.push('#endif /* CYGNUS_IDS_H */', '');
  return out.join('\n');
}

// ---- STATUS tables -----------------------------------------------------------------------

export interface FieldRow {
  name: string;
  byte: number;
  size: number;
  signed: boolean;
  isFloat: boolean;
  bit: number;
  bits: number;
  scale: number;
  bias: number;
}

export function fieldRow(f: StatusFieldDef): FieldRow {
  return {
    name: sig(f.signal),
    byte: f.byte,
    size: FIELD_SIZE[f.type],
    signed: f.type.startsWith('i') || f.type === 'f32',
    isFloat: f.type === 'f32',
    bit: f.bit ?? 0,
    bits: f.bits ?? 0,
    scale: f.scale ?? 1,
    bias: f.bias ?? 0,
  };
}

const uniqueModels = (cards: readonly NamedCard[]): NamedCard[] => cards.filter((c, i) => c.def && cards.findIndex((x) => x.model === c.model) === i);
const frameFields = (f: StatusFrameDef): FieldRow[] => f.fields.map(fieldRow);

function cppTable(model: NamedCard, f: StatusFrameDef): string[] {
  const tag = `${model.modelKey.toUpperCase()}_STATUS${f.index}`;
  const rows = frameFields(f).map(
    (r) => `  { "${r.name}", ${r.byte}, ${r.size}, ${r.signed}, ${r.isFloat}, ${r.bit}, ${r.bits}, ${lit(r.scale)}f, ${lit(r.bias)}f },`,
  );
  return [`static const CyField ${tag}[] = {`, ...rows, '};', `static const uint8_t ${tag}_COUNT = ${f.fields.length};`];
}

// ---- Arduino (C++) -----------------------------------------------------------------------

export const ARDUINO_DECODE_BEGIN = '// --- cygnus:decode begin';
export const ARDUINO_DECODE_END = '// --- cygnus:decode end';

export function genArduino(cards: readonly CodeCard[], text: CodeText): string {
  const named = nameCards(cards);
  const withDef = named.filter((c) => c.def);
  const models = uniqueModels(named);
  const first = withDef[0];
  const out: string[] = [];
  out.push(noticeBlock({ ...text, notice: ['Generated by Cygnus Studio (Arduino / C++ skeleton).', `Source: ${text.source}`, '', ...text.notice, '', 'Uses the third-party MCP2515 driver "autowp/arduino-mcp2515" (not made by Cygnus).', 'MCP2515 speaks classic CAN only: set can.data_bitrate = 0 on the boards (PROTOCOL 1).', 'Assumes an 8 MHz crystal on the MCP2515 module and chip select on pin 10.'] }, '/*', ' * ', ' */'));
  out.push('#include <SPI.h>', '#include <mcp2515.h>', '#include <string.h>', '#include "cygnus_ids.h"  // generated by the "C header" snippet', '');
  out.push('MCP2515 mcp2515(10);', '');
  out.push(ARDUINO_DECODE_BEGIN);
  out.push('struct CyField {', '  const char *name;', '  uint8_t byte;', '  uint8_t size;', '  bool isSigned;', '  bool isFloat;', '  uint8_t bit;', '  uint8_t bits;', '  float scale;', '  float bias;', '};', '');
  out.push(
    'static float cyDecode(const uint8_t *d, const CyField &f) {',
    '  if (f.isFloat) {',
    '    float v;',
    '    memcpy(&v, d + f.byte, 4);',
    '    return v;',
    '  }',
    '  uint32_t raw = 0;',
    '  for (uint8_t i = 0; i < f.size; i++) raw |= (uint32_t)d[f.byte + i] << (8 * i);',
    '  if (f.bits) return (float)((raw >> f.bit) & ((1UL << f.bits) - 1)) * f.scale + f.bias;',
    '  if (f.isSigned) {',
    '    uint8_t shift = 32 - 8 * f.size;',
    '    int32_t v = (int32_t)(raw << shift) >> shift;',
    '    return (float)v * f.scale + f.bias;',
    '  }',
    '  return (float)raw * f.scale + f.bias;',
    '}',
    '',
  );
  for (const m of models) for (const f of m.def?.statusFrames ?? []) out.push(`// ${m.def?.name.en ?? m.modelKey}, STATUS ${f.index}: ${f.label.en} (every ${f.defaultPeriodMs} ms by default)`, ...cppTable(m, f), '');
  out.push(ARDUINO_DECODE_END, '');
  out.push(
    'static void printStatus(const char *who, const CyField *fields, uint8_t count, const uint8_t *data) {',
    '  Serial.print(who);',
    '  for (uint8_t i = 0; i < count; i++) {',
    '    Serial.print(\' \');',
    '    Serial.print(fields[i].name);',
    '    Serial.print(\'=\');',
    '    Serial.print(cyDecode(data, fields[i]), 4);',
    '  }',
    '  Serial.println();',
    '}',
    '',
  );
  out.push('void setup() {', '  Serial.begin(115200);', '  mcp2515.reset();', '  mcp2515.setBitrate(CAN_1000KBPS, MCP_8MHZ);', '  mcp2515.setNormalMode();', '');
  if (first) {
    out.push(`  // Raw frame example: IDENTIFY ${first.ident} for 3 seconds (SYS_REQ index 2, payload = [seconds]).`);
    out.push('  struct can_frame tx;', `  tx.can_id = ${first.ident}_ID_IDENTIFY | CAN_EFF_FLAG;`, '  tx.can_dlc = 1;', '  tx.data[0] = 3;', '  mcp2515.sendMessage(&tx);');
  }
  out.push('}', '');
  out.push('void loop() {', '  struct can_frame rx;', '  if (mcp2515.readMessage(&rx) != MCP2515::ERROR_OK) return;', '  if (!(rx.can_id & CAN_EFF_FLAG)) return;  // Cygnus uses 29-bit identifiers only', '  uint32_t id = rx.can_id & CAN_EFF_MASK;', '');
  for (const c of withDef) {
    const tag = c.modelKey.toUpperCase();
    for (const f of c.def?.statusFrames ?? []) out.push(`  if (id == ${c.ident}_ID_STATUS${f.index}) printStatus("${c.ident}", ${tag}_STATUS${f.index}, ${tag}_STATUS${f.index}_COUNT, rx.data);`);
  }
  out.push('}', '');
  return out.join('\n');
}

// ---- Python ------------------------------------------------------------------------------

export function genPython(cards: readonly CodeCard[], text: CodeText): string {
  const named = nameCards(cards);
  const withDef = named.filter((c) => c.def);
  const models = uniqueModels(named);
  const first = withDef[0];
  const out: string[] = [];
  out.push('"""' + ['Generated by Cygnus Studio (Python skeleton).', `Source: ${text.source}`, '', ...text.notice, '', 'The optional bus access below uses the third-party "python-can" package (not made by Cygnus).'].join('\n') + '\n"""');
  out.push('import struct', '');
  out.push(`MFR = ${MFR}`, `CLS_CTRL = 0x${Cls.CTRL.toString(16)}`, `CLS_STATUS = 0x${Cls.STATUS.toString(16)}`, `CLS_SYS_REQ = 0x${Cls.SYS_REQ.toString(16)}`, `CLS_SYS_RSP = 0x${Cls.SYS_RSP.toString(16)}`, `SYS_REQ_IDENTIFY = ${SysReq.IDENTIFY}`, '');
  out.push(
    'def can_id(devtype, cls, index, num):',
    '    """29-bit identifier: DEVTYPE[28:24] MFR[23:16] CLASS[15:10] INDEX[9:6] NUM[5:0]."""',
    '    return ((devtype & 0x1F) << 24) | ((MFR & 0xFF) << 16) | ((cls & 0x3F) << 10) | ((index & 0x0F) << 6) | (num & 0x3F)',
    '',
    '',
    'def split_id(arbitration_id):',
    '    return ((arbitration_id >> 24) & 0x1F, (arbitration_id >> 16) & 0xFF, (arbitration_id >> 10) & 0x3F, (arbitration_id >> 6) & 0x0F, arbitration_id & 0x3F)',
    '',
    '',
  );
  out.push('DEVICES = {');
  for (const c of named) out.push(`    "${c.ident}": {"devtype": ${c.devType}, "num": ${c.num}, "model": "${c.modelKey}"},`);
  out.push('}', '');
  out.push('# STATUS layouts from the catalog: (signal, byte, size, signed, is_float, bit, bits, scale, bias)');
  out.push('STATUS_LAYOUT = {');
  for (const m of models) {
    out.push(`    "${m.modelKey}": {`);
    for (const f of m.def?.statusFrames ?? []) {
      out.push(`        ${f.index}: [  # ${f.label.en}`);
      for (const r of frameFields(f)) out.push(`            ("${r.name}", ${r.byte}, ${r.size}, ${r.signed ? 'True' : 'False'}, ${r.isFloat ? 'True' : 'False'}, ${r.bit}, ${r.bits}, ${lit(r.scale)}, ${lit(r.bias)}),`);
      out.push('        ],');
    }
    out.push('    },');
  }
  out.push('}', '');
  out.push(
    '',
    'def decode_status(model, index, data):',
    '    """Decode an 8-byte STATUS payload to {signal: physical value}."""',
    '    values = {}',
    '    for name, off, size, signed, is_float, bit, bits, scale, bias in STATUS_LAYOUT[model][index]:',
    '        if is_float:',
    '            values[name] = struct.unpack_from("<f", data, off)[0]',
    '            continue',
    '        raw = int.from_bytes(bytes(data[off:off + size]), "little", signed=False)',
    '        if bits:',
    '            raw = (raw >> bit) & ((1 << bits) - 1)',
    '        elif signed and raw >= 1 << (8 * size - 1):',
    '            raw -= 1 << (8 * size)',
    '        values[name] = raw * scale + bias',
    '    return values',
    '',
    '',
  );
  out.push('def main():', '    import can  # pip install python-can', '');
  out.push('    # Pick the interface of your adapter, e.g. interface="slcan", channel="/dev/ttyACM0", bitrate=1000000.');
  out.push('    with can.Bus(interface="socketcan", channel="can0") as bus:');
  if (first) {
    out.push(`        # Raw frame example: IDENTIFY ${first.ident} for 3 seconds (payload = [seconds]).`);
    out.push(`        d = DEVICES["${first.ident}"]`, '        bus.send(can.Message(arbitration_id=can_id(d["devtype"], CLS_SYS_REQ, SYS_REQ_IDENTIFY, d["num"]), is_extended_id=True, data=[3]))', '');
  }
  out.push(
    '        while True:',
    '            msg = bus.recv(timeout=1.0)',
    '            if msg is None or not msg.is_extended_id:',
    '                continue',
    '            devtype, mfr, cls, index, num = split_id(msg.arbitration_id)',
    '            if mfr != MFR or cls != CLS_STATUS:',
    '                continue',
    '            for name, d in DEVICES.items():',
    '                if (d["devtype"], d["num"]) == (devtype, num) and d["model"] in STATUS_LAYOUT and index in STATUS_LAYOUT[d["model"]]:',
    '                    print(name, index, decode_status(d["model"], index, msg.data))',
    '',
    '',
    'if __name__ == "__main__":',
    '    main()',
    '',
  );
  return out.join('\n');
}

export type CodeKind = 'c' | 'arduino' | 'python';

export const CODE_FILES: Record<CodeKind, { file: string; mime: string }> = {
  c: { file: 'cygnus_ids.h', mime: 'text/x-chdr' },
  arduino: { file: 'cygnus_status.ino', mime: 'text/x-c++src' },
  python: { file: 'cygnus_status.py', mime: 'text/x-python' },
};

export function generate(kind: CodeKind, cards: readonly CodeCard[], text: CodeText): string {
  return kind === 'c' ? genCHeader(cards, text) : kind === 'arduino' ? genArduino(cards, text) : genPython(cards, text);
}
